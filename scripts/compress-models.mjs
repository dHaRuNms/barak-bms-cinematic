import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { dedup, prune, weld, meshopt } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import { readdir, stat, writeFile } from 'node:fs/promises';
await Promise.all([MeshoptEncoder.ready, MeshoptDecoder.ready]);
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.encoder':MeshoptEncoder,'meshopt.decoder':MeshoptDecoder});
const manifest=[];
for (const file of await readdir('public/models')) {
 if (!file.endsWith('.glb')) continue;
 const path=`public/models/${file}`, before=(await stat(path)).size, document=await io.read(path);
 await document.transform(dedup(),weld(),prune(),meshopt({encoder:MeshoptEncoder,level:'medium'}));
 await io.write(path,document); const after=(await stat(path)).size;
 manifest.push({file,bytes:after,source:'Original procedural geometry authored for Barak; generated by scripts/generate-models.mjs',compression:'EXT_meshopt_compression'});
 console.log(`${file}: ${Math.round(before/1024)} → ${Math.round(after/1024)} KB`);
}
await writeFile('public/models/manifest.json',JSON.stringify(manifest,null,2));
